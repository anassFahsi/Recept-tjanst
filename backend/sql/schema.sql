-- ============================
-- MEMBERSHIP LEVELS
-- ============================
CREATE TABLE membership_levels (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  slug VARCHAR(100) UNIQUE NOT NULL,
  tier INT NOT NULL,
  price_ore INT NOT NULL,
  max_saved_recipes INT NOT NULL,
  description TEXT
);

