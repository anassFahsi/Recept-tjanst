-- ============================
-- RECIPES
-- ============================
CREATE TABLE recipes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE NOT NULL,
  required_level_id INT REFERENCES membership_levels(id),
  category_id INT REFERENCES categories(id),
  intro TEXT,
  instructions TEXT[] NOT NULL,
  image_url VARCHAR(255),
  cook_time_min INT,
  is_published BOOLEAN DEFAULT FALSE,
  created_by INT REFERENCES users(id),
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW()
);

-- ============================
-- RECIPE INGREDIENTS
-- ============================
CREATE TABLE recipe_ingredients (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id INT REFERENCES recipes(id) ON DELETE CASCADE,
  name VARCHAR(255) NOT NULL,
  amount decimal,
  unit VARCHAR(50),
  sort_order INT DEFAULT 0
);

-- ============================
-- SAVED RECIPES (MANY-TO-MANY)
-- ============================
CREATE TABLE saved_recipes (
  user_id INT REFERENCES users(id) ON DELETE CASCADE,
  recipe_id INT REFERENCES recipes(id) ON DELETE CASCADE,
  saved_at TIMESTAMP DEFAULT NOW(),
  PRIMARY KEY (user_id, recipe_id)
);

-- ============================
-- RECEIPTS (BETALNINGAR)
-- ============================
CREATE TABLE receipts (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT REFERENCES users(id),
  membership_level_id INT REFERENCES membership_levels(id),
  order_reference VARCHAR(255) NOT NULL,
  amount_ore INT NOT NULL,
  level_name_snapshot VARCHAR(255) NOT NULL,
  status VARCHAR(50) NOT NULL,
  paid_at TIMESTAMP DEFAULT NOW()
);










